def _norm(s: str) -> str:
    """归一化：去所有空白（含单元格内换行）、全角空格、繁转简、转小写。

    2026-09-29：客户表国家列里有「德国\\n开发客户」这种**单元格内换行**的写法，
    所以这里把 \\r\\n\\t 全去掉，让「德国开发客户」成为一个连续串好做前缀匹配。
    """
    t = (s or "").strip()
    for ch in ("\r", "\n", "\t", " ", "　", " ", "_"):
        t = t.replace(ch, "")
    t = "".join(_T2S.get(c, c) for c in t)
    return t.lower()


