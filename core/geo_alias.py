def _has_cjk(s: str) -> bool:
    return any(ord(c) > 0x2E80 for c in s)


def _full_lookup(key: str) -> tuple[str, str]:
    """整串完全匹配。返回 (标准国家名, 说明)；没命中返回 ("", "")。"""
    if not key:
        return "", ""
    if key in _AMBIGUOUS:
        return "", "amb"
    m = _user_map().get(key)
    if m:
        return str(m).strip(), "自定义映射"
    m = _COUNTRY_CN.get(key)
    if m:
        return m, "标准国家名"
    m = _SHORT_CN.get(key) if len(key) <= 2 else ""
    if m:
        return m, "简称"
    m = _COUNTRY_EN.get(key)
    if m:
        return m, "英文名"
    m = _CITY2COUNTRY.get(key)
    if m:
        return m, "城市→国家"
    return "", ""


def _prefix_lookup(key: str) -> tuple[str, str]:
    """最长前缀匹配 —— 「国家名 + 后面跟了别的内容」专用。

    例：「德国开发客户」→ 依次试 德国开发客 / 德国开发 / 德国开 / 德国 ✓
    安全边界：只匹配**含中日韩汉字**的前缀，英文公司名不会被误伤。
    """
    for n in range(len(key) - 1, 1, -1):
        sub = key[:n]
        if not _has_cjk(sub):
            continue                      # 纯英文前缀不参与，防止把公司名当国家
        if sub in _AMBIGUOUS:
            return "", "amb"
        m = _user_map().get(sub)
        if m:
            return str(m).strip(), "前缀：自定义映射"
        m = _COUNTRY_CN.get(sub)
        if m:
            return m, "前缀：标准国家名"
        m = _CITY2COUNTRY.get(sub)
        if m:
            return m, "前缀：城市→国家"
    return "", ""


# 单元格里常见的分隔写法：斜杠、逗号、分号、顿号、竖线、破折号
_SPLIT_RE = re.compile(r"[/\\,，;；、|｜·．.\-—–]+")
# 括号里的内容优先当国家看：「（阿联酋）迪拜」
_BRACKET_RE = re.compile(r"[（(\[【]([^）)\]】]{1,20})[）)\]】]")


def resolve_country(name: str) -> tuple[str, str]:
    """把客户表里的国家串换算成孚盟认得的国家名。

    2026-09-29 增强：客户表常写成「国家名 + 后缀」，识别顺序如下
      ① 整串完全匹配
      ② 括号里的内容（「（阿联酋）迪拜」→ 阿联酋）
      ③ 按分隔符切片段（「德国-开发客户」→ 德国）
      ④ 最长前缀匹配（「美国广交会客户」→ 美国、「沙特sa」→ 沙特阿拉伯）

    返回 (新名字, 说明)：没匹配上时返回 ("", "") —— 调用方保持原名即可。
    返回 ("", "amb") 表示是地区泛称（欧盟/中东…），必须人工改客户表。
    """
    raw = (name or "").strip()
    key = _norm(raw)
    if not key:
        return "", ""

    # ① 整串完全匹配
    c, note = _full_lookup(key)
    if c or note:
        return c, note

    # ② 括号里的内容优先：「（阿联酋）迪拜」「迪拜(阿联酋)」
    for seg in _BRACKET_RE.findall(raw):
        c, note = _full_lookup(_norm(seg))
        if c or note == "amb":
            return c, note

    # ③ 按分隔符切片段，逐个完全匹配
    for seg in _SPLIT_RE.split(raw):
        c, note = _full_lookup(_norm(seg))
        if c:
            return c, note + "（拼接串）"
        if note == "amb":
            return "", "amb"

    # ④ 最长前缀匹配（只认中文前缀）
    return _prefix_lookup(key)


def strip_prefix(country: str) -> str:
    """孚盟下拉里的条目名通常不含「中国」前缀，搜索时用短名更准。"""
    c = (country or "").strip()
    for p in ("中国香港", "中国澳门", "中国台湾"):
        if c == p:
            return p[2:]          # 中国香港 → 香港
    return c


def search_terms(country: str) -> list[str]:
    """给一个客户表里的国家串，返回按优先级排好的【搜索词】列表。

    2026-09-29：如果原串确实带后缀（「美国广交会客户」），
    **换算出来的干净国家名排第一** —— 否则孚盟会先拿脏串白搜一次（十几秒）。
    原串仍然保留在后面当兜底（万一孚盟的条目名就是这么写的）。
    """
    raw = (country or "").strip()
    mapped, _note = resolve_country(raw)
    m = strip_prefix(mapped) if mapped else ""
    out = []
    if m:
        if _norm(m) != _norm(raw):
            out.append(m)          # 原串带后缀 → 干净名优先
            out.append(raw)        # 兜底
        else:
            out.append(raw)
    else:
        out.append(raw)
    # 去重且保序
    seen = set()
    r = []
    for x in out:
        if x and x not in seen:
            seen.add(x)
            r.append(x)
    return r


def suggest_alias(name: str) -> str:
    """给人看的提示语：这个名称该怎么改。"""
    c, note = resolve_country(name)
    if c and note != "amb":
        return f"「{name}」→ 已自动换算为「{c}」"
    if note == "amb":
        return f"「{name}」是地区泛称，请改成具体国家名"
    return ""
